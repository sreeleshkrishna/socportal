const mmType = (t: string) =>
  (({ 'timestamp with time zone': 'timestamptz', 'character varying': 'varchar', ARRAY: 'array', 'double precision': 'float' } as Record<string, string>)[t] ?? t)
    .replace(/\s+/g, '_');

const db = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const dbData = await (async () => {
  try {
    const cols = await db.query(
      `select table_name, column_name, data_type, is_nullable, column_default
       from information_schema.columns
       where table_schema = 'public' and table_name <> 'schema_migrations'
       order by table_name, ordinal_position`);
    const pks = await db.query(
      `select tc.table_name, kcu.column_name
       from information_schema.table_constraints tc
       join information_schema.key_column_usage kcu
         on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
       where tc.table_schema = 'public' and tc.constraint_type = 'PRIMARY KEY'`);
    const fks = await db.query(
      `select c.conrelid::regclass::text as child, c.confrelid::regclass::text as parent, a.attname as col
       from pg_constraint c
       join pg_attribute a on a.attrelid = c.conrelid and a.attnum = any (c.conkey)
       where c.contype = 'f' and c.connamespace = 'public'::regnamespace`);
    const counts = await db.query(
      `select (select count(*)::int from playbooks) as playbooks,
              (select count(*)::int from playbook_tasks) as playbook_tasks,
              (select count(*)::int from attack_techniques) as techniques`);
    return { cols: cols.rows, pks: pks.rows, fks: fks.rows, counts: counts.rows[0] };
  } finally {
    await db.end();
  }
})();

interface Col { name: string; type: string; nullable: boolean; def: string | null }
const tables = new Map<string, Col[]>();
for (const r of dbData.cols) {
  const list = tables.get(r.table_name) ?? [];
  list.push({ name: r.column_name, type: r.data_type, nullable: r.is_nullable === 'YES', def: r.column_default });
  tables.set(r.table_name, list);
}
const pkSet = new Set(dbData.pks.map((r: any) => `${r.table_name}.${r.column_name}`));
const fkSet = new Set(dbData.fks.map((r: any) => `${r.child}.${r.col}`));
const keyOf = (t: string, c: string) =>
  [pkSet.has(`${t}.${c}`) ? 'PK' : '', fkSet.has(`${t}.${c}`) ? 'FK' : ''].filter(Boolean).join(', ');
const sorted = [...tables].sort(([a], [b]) => a.localeCompare(b));
const uniqueFks = [...new Map(dbData.fks.map((r: any) => [`${r.parent}|${r.child}|${r.col}`, r])).values()] as any[];

const dm = [
  '# Data model', '', NOTE, '',
  `${tables.size} tables, created by the SQL files in \`backend/migrations\`. The diagram shows keys only for readability; a data dictionary follows.`, '',
  FENCE + 'mermaid', 'erDiagram',
  ...uniqueFks.map((r) => `    ${r.parent} ||--o{ ${r.child} : "${r.col}"`),
  ...sorted.flatMap(([name, cs]) => [
    `    ${name} {`,
    ...cs.map((c) => `        ${mmType(c.type)} ${c.name}${keyOf(name, c.name) ? ' ' + keyOf(name, c.name) : ''}`),
    '    }',
  ]),
  FENCE, '',
  '## Data dictionary', '',
];
for (const [name, cs] of sorted) {
  dm.push(`### ${name}`, '', TABLE_NOTES[name] ?? '', '', '| Column | Type | Null | Key | Default |', '|---|---|---|---|---|');
  for (const c of cs) {
    const def = c.def ? '`' + c.def.slice(0, 40).replace(/\|/g, '/') + '`' : '';
    dm.push(`| \`${c.name}\` | ${c.type} | ${c.nullable ? 'yes' : 'no'} | ${keyOf(name, c.name)} | ${def} |`);
  }
  dm.push('');
}
await save('data-model.md', dm);

