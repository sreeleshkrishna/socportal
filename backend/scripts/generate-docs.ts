async function countLines(dir: string, re: RegExp): Promise<{ files: number; lines: number }> {
  let files = 0, lines = 0;
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      const r = await countLines(p, re);
      files += r.files; lines += r.lines;
    } else if (re.test(e.name)) {
      files++; lines += (await readFile(p, 'utf8')).split('\n').length;
    }
  }
  return { files, lines };
}
